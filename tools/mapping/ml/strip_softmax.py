#!/usr/bin/env python3
"""Strip the trailing Softmax op from a TFLite classifier and expose logits.

The on-device ESP_TF/TFLite-Micro softmax Prepare path aborts on this board
(`QuantizeMultiplierGreaterThanOne`) for the trained empty/human model even
though the same model runs in the desktop interpreter. Keeping the model's
logits output and applying softmax in float32 on the ESP32-S3 removes that
fragile kernel path without changing the trained weights or quantization.

Usage:
  python strip_softmax.py --input model-empty-human-v2/model.tflite \
      --output model-empty-human-v2-logits

The output directory receives model.tflite and model_data.h. The companion
model_metadata.h must be copied/renamed from the source model (same mean/std/
labels) with a `-logits` version suffix.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import flatbuffers
from tensorflow.lite.python import schema_py_generated as schema

SOFTMAX = 25


def strip_softmax(data: bytes) -> tuple[bytes, int]:
    model = schema.ModelT.InitFromObj(schema.Model.GetRootAsModel(data, 0))
    removed = 0
    for subgraph in model.subgraphs:
        changed = True
        while changed:
            changed = False
            for index, op in enumerate(subgraph.operators):
                code = model.operatorCodes[op.opcodeIndex].builtinCode
                if code != SOFTMAX:
                    continue
                source = op.inputs[0]
                target = op.outputs[0]
                del subgraph.operators[index]
                subgraph.outputs = [source if item == target else item
                                    for item in subgraph.outputs]
                removed += 1
                changed = True
                break
    builder = flatbuffers.Builder(0)
    builder.Finish(model.Pack(builder), file_identifier=b"TFL3")
    return bytes(builder.Output()), removed


def write_header(tflite: bytes, path: Path) -> None:
    lines = ["// Generated by tools/mapping/ml/strip_softmax.py", "#pragma once",
             "#include <stdint.h>", ""]
    lines.append("alignas(16) const unsigned char g_model[] = {")
    for offset in range(0, len(tflite), 16):
        lines.append("  " + ",".join(str(byte) for byte in tflite[offset:offset + 16]) + ",")
    lines.append("};")
    lines.append(f"const unsigned int g_model_len = {len(tflite)};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    data = args.input.read_bytes()
    stripped, removed = strip_softmax(data)
    if removed != 1:
        raise SystemExit(f"expected exactly one Softmax op, removed {removed}")
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "model.tflite").write_bytes(stripped)
    write_header(stripped, args.output / "model_data.h")
    print(json.dumps({
        "input": str(args.input), "input_bytes": len(data),
        "output": str(args.output / "model.tflite"), "output_bytes": len(stripped),
        "softmax_ops_removed": removed,
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
